namespace RuangMeetingApi.Models;

/// <summary>Row of dbo.RUANGAN.</summary>
public class Ruangan
{
    public int RuanganId { get; set; }
    public string KodeRuangan { get; set; } = "";
    public string NamaRuangan { get; set; } = "";
    public string Lokasi { get; set; } = "";
    public int Kapasitas { get; set; }
    public bool IsAktif { get; set; } = true;
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }
    public byte[] RowVer { get; set; } = [];
}

/// <summary>Row of dbo.RESERVASI.</summary>
public class Reservasi
{
    public long ReservasiId { get; set; }
    public string KodeReservasi { get; set; } = null!; // generated by the DB (sequence)
    public int RuanganId { get; set; }
    public Ruangan? Ruangan { get; set; }
    public string NamaPemesan { get; set; } = "";
    public string JudulMeeting { get; set; } = "";
    public DateOnly Tanggal { get; set; }
    public TimeOnly JamMulai { get; set; }
    public TimeOnly JamSelesai { get; set; }
    public int JumlahPeserta { get; set; }
    public string Status { get; set; } = StatusReservasi.Booked;
    public Guid IdempotencyKey { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }
    public byte[] RowVer { get; set; } = [];
}

public static class StatusReservasi
{
    public const string Booked = "BOOKED";       // active: blocks the time slot
    public const string Cancelled = "CANCELLED";
    public const string Completed = "COMPLETED";
    public static readonly string[] Semua = [Booked, Cancelled, Completed];
}
